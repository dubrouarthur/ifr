const D: Record<Lang, Dict> = { en: EN, fr: FR };

/** a debrief string in the given language ({name} bound); FR falls back to EN, then to the key */
export function dx(
  l: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const s = D[l][key] ?? EN[key] ?? key;
  return vars
    ? s.replace(/\{(\w+)\}/g, (m, k: string) =>
        k in vars ? String(vars[k]) : m,
      )
    : s;
}
/** a debrief string in the app language */
export const drt = (key: string, vars?: Record<string, string | number>) =>
  dx(curLang(), key, vars);
/** every key exists in both languages (tests) */
export const DEBRIEF_KEYS = { en: Object.keys(EN), fr: Object.keys(FR) };
