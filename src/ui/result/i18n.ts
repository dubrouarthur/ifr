export const STRINGS: Record<Lang, Dict> = { en: EN, fr: FR };

/** a string in the given language ({name} bound from vars); FR falls back to EN, then to the key */
export function tx(
  l: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const s = STRINGS[l][key] ?? EN[key] ?? key;
  return vars
    ? s.replace(/\{(\w+)\}/g, (m, k: string) =>
        k in vars ? String(vars[k]) : m,
      )
    : s;
}

/** the app's language */
export const curLang = (): Lang => (uiLang() === "fr" ? "fr" : "en");
/** a string in the app's language */
export const rt = (key: string, vars?: Record<string, string | number>) =>
  tx(curLang(), key, vars);

/** thousands as the language writes them (2,227 / 2 227) */
export function num(l: Lang, v: number, digits = 0): string {
  const s = Math.abs(v).toFixed(digits);
  const [i, d] = s.split(".");
  const sep = l === "fr" ? " " : ",";
  const int = i.length > 3 ? i.replace(/\B(?=(\d{3})+(?!\d))/g, sep) : i;
  const out = d ? `${int}${l === "fr" ? "," : "."}${d}` : int;
  return v < 0 ? `−${out}` : out;
}
/** signed with an explicit + (deviations) */
export const sgn = (l: Lang, v: number, digits = 0) =>
  v > 0 ? `+${num(l, v, digits)}` : num(l, v, digits);

/** m:ss */
export function mmss(sec: number): string {
  const s = Math.max(0, Math.round(sec));
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}`;
}
